    /** NATIVE 容器桌面模式视口与 screen/outerWidth 对齐脚本 */
    public static String buildNativeDesktopScript(int targetWidth, double scale, boolean autoFitDip) {
        int w = targetWidth > 0 ? targetWidth : ContainerEnv.DESKTOP_VIEWPORT_W;
        int h = ContainerEnv.DESKTOP_VIEWPORT_H;
        String vpScript = buildDesktopViewportMetaScript(w, scale, autoFitDip);
        String alignScript = String.join("\n",
                "(function(W_DEF, H_DEF){",
                "  'use strict';",
                "  try {",
                "    var W = typeof window !== 'undefined' ? window : globalThis;",
                "    var defGet = function(obj, prop, fn) {",
                "      if (!obj) return;",
                "      var prev = null;",
                "      try { prev = Object.getOwnPropertyDescriptor(obj, prop); } catch (e) {}",
                "      if (prev && prev.configurable === false) return;",
                "      try {",
                "        Object.defineProperty(obj, prop, {",
                "          get: fn,",
                "          enumerable: prev ? !!prev.enumerable : true,",
                "          configurable: true",
                "        });",
                "      } catch (e) {}",
                "    };",
                "    defGet(W, 'outerWidth', function() { return Math.max(W_DEF, W.innerWidth || 0); });",
                "    defGet(W, 'outerHeight', function() {",
                "      var sh = Math.max(H_DEF, W.innerHeight || 0);",
                "      return Math.min(sh, Math.max(H_DEF, (W.innerHeight || 0) + 72));",
                "    });",
                "    var sp = typeof Screen !== 'undefined' ? Screen.prototype : (W.screen ? Object.getPrototypeOf(W.screen) : null);",
                "    if (sp) {",
                "      defGet(sp, 'width', function() { return Math.max(W_DEF, W.innerWidth || 0); });",
                "      defGet(sp, 'height', function() { return Math.max(H_DEF, W.innerHeight || 0); });",
                "      defGet(sp, 'availWidth', function() { return Math.max(W_DEF, W.innerWidth || 0); });",
                "      defGet(sp, 'availHeight', function() { return Math.max(0, Math.max(H_DEF, W.innerHeight || 0) - 40); });",
                "    }",
                "  } catch (e) {}",
                "})(" + w + ", " + h + ");"
        );
        return vpScript + "\n" + alignScript;
    }
